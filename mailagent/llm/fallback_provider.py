"""Deterministic fallback provider for demo mode when AI is unavailable."""

import hashlib
import logging
from typing import Any, AsyncIterator, Dict, List, Optional, Sequence

from mailagent.llm.base import (
    LLMMessage,
    LLMProvider,
    LLMResponse,
    LLMTool,
    ProviderCapabilities,
)

logger = logging.getLogger(__name__)


class FallbackProvider(LLMProvider):
    """Deterministic fallback provider for demo mode when external AI is unavailable."""

    provider_name = "fallback"

    def __init__(self):
        self.api_url = "internal://fallback"

    @property
    def capabilities(self) -> ProviderCapabilities:
        return ProviderCapabilities(
            supports_tools=False,
            supports_json_mode=False,
            context_window=0,
        )

    async def complete(
        self,
        messages: Sequence[LLMMessage],
        *,
        model: str,
        tools: Sequence[LLMTool] = (),
        response_schema: Optional[Dict[str, Any]] = None,
        json_mode: bool = False,
        max_tokens: int = 512,
        timeout_seconds: float = 30,
    ) -> LLMResponse:
        """Return deterministic fallback responses based on input hash."""

        # Create a hash of the input for deterministic responses
        content = "\n".join([f"{m.role}: {m.content}" for m in messages])
        input_hash = hashlib.md5(content.encode()).hexdigest()

        # Generate deterministic responses based on hash
        if "classify" in content.lower() or "priority" in content.lower():
            # Classification response
            hash_int = int(input_hash[:8], 16)
            priority = 50 + (hash_int % 50)  # 50-99
            categories = ["urgent", "meets_reply", "sensitive", "FYI", "newsletter", "promo"]
            category = categories[hash_int % len(categories)]
            actions = ["reply", "archive", "draft_only"]
            action = actions[hash_int % len(actions)]

            response_text = f"""{
  "category": "{category}",
  "priority_score": {priority},
  "action": "{action}",
  "confidence": 0.85,
  "reason": "This is a deterministic fallback classification. In a real deployment, this would be generated by an AI model."
}"""
        elif "draft" in content.lower() or "reply" in content.lower():
            # Draft response — extract subject and body for more contextual template
            hash_int = int(input_hash[:8], 16)
            # Try to extract subject line from the prompt for a more contextual reply
            subject_line = ""
            body_content = ""
            for line in content.split("\n"):
                if line.strip().lower().startswith("subject:"):
                    subject_line = line.strip()[len("subject:"):].strip()
                # Try to capture the body after Subject line
                if subject_line and line.strip() and not line.strip().lower().startswith("subject:"):
                    body_content += line + "\n"

            # Check if the email asks for a choice (e.g., "4 PM or 6 PM")
            body_lower = body_content.lower()
            asks_for_choice = any(
                indicator in body_lower
                for indicator in [" or ", "would you prefer", "which time", "which option", "choose between"]
            )

            if subject_line and asks_for_choice:
                # If asking for a choice, acknowledge and ask for clarification
                response_text = f"""Hi,

Thank you for reaching out regarding "{subject_line}".

I see you've offered a few options - could you let me know which would work best for you, or provide more context about your preference?

I'll review the details and follow up as soon as possible.

Best regards"""
            elif subject_line:
                response_text = f"""Hi,

Thank you for reaching out regarding "{subject_line}".

I've received your message and will review the details. I'll get back to you with a specific response shortly.

Please let me know if this is time-sensitive.

Best regards"""
            else:
                response_text = """Hi,

Thank you for your message. I've received it and will review the details.

I'll follow up with a specific response as soon as possible.

Best regards"""
        else:
            # Generic response
            response_text = "This is a deterministic fallback response. Configure an AI provider (OpenRouter or Claude) for real AI-generated responses."

        logger.warning("Using deterministic fallback response (provider unavailable)")

        return LLMResponse(
            text=response_text,
            tool_calls=[],
            input_tokens=len(content.split()),
            output_tokens=len(response_text.split()),
            model="fallback-deterministic",
            provider=self.provider_name,
            raw={
                "fallback": True,
                "input_hash": input_hash,
                "is_fallback": True,  # Explicit marker for easy detection
                "reason": "This is a deterministic fallback classification. In a real deployment, this would be generated by an AI model."
            },
        )

    async def stream(
        self,
        messages: Sequence[LLMMessage],
        *,
        model: str,
        max_tokens: int = 512,
    ) -> AsyncIterator[str]:
        """Stream completion using fallback (non-streaming)."""

        response = await self.complete(messages, model=model, max_tokens=max_tokens)
        yield response.text
