@pytest.mark.asyncio
async def test_kill_switch_prevents_local_queue_scheduling():
    """LocalTaskQueue must refuse to schedule tasks when kill switch is active."""
    from mailagent.core.local_queue import LocalTaskQueue

    kill_switch_active = True
    queue = LocalTaskQueue(
        db_path=":memory:",
        kill_switch_checker=lambda: kill_switch_active,
    )
    await queue.start()
    try:
        result = queue.schedule_task("test-task", lambda: None, interval_seconds=60)
        assert result is False
    finally:
        await queue.stop()


