# 8. Send flow: idempotency (duplicate send prevention)
# ---------------------------------------------------------------------------

@pytest.mark.asyncio
async def test_send_flow_idempotency_rejects_duplicate():
    from mailagent.policy.send_flow import SendFlow
    from mailagent.core.types import EmailAction, Draft, DraftStatus, AutonomyMode

    flow = SendFlow(autonomy_mode=AutonomyMode.APPROVE)
    draft = Draft(
        email_id="email-1", classification_id="clf-1", content="Thanks!",
        status=DraftStatus.PENDING
    )
    # Mark as already sent
    flow.record_sent("email-1")
    status, reason = await flow.process_draft(draft, EmailAction.REPLY)
    assert status == DraftStatus.REJECTED
    assert "already" in reason.lower()


