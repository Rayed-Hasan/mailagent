# 1. Desktop wrapper: token must be unpredictable (32 random bytes = 64 hex chars)
# ---------------------------------------------------------------------------

def test_desktop_token_length_and_entropy():
    """The ephemeral token generated by the Electron main process must be at
    least 256 bits of randomness. We verify the generation formula here."""
    import hashlib
    token = secrets.token_hex(32)  # same formula as desktop/main.js
    assert len(token) == 64, "Token must be 64 hex chars (256 bits)"
    # Verify uniqueness — two tokens must not collide
    token2 = secrets.token_hex(32)
    assert token != token2


