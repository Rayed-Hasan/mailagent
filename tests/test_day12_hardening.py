# 5. Transactional delete: all child records removed
# ---------------------------------------------------------------------------

@pytest.mark.asyncio
async def test_delete_user_data_removes_all_child_records():
    """delete_user_data must remove emails, labels, drafts, and classifications."""
    from mailagent.core.sqlite_storage import SQLiteStorage
    import aiosqlite
    import uuid

    key = make_32_byte_key()
    with patch.dict(os.environ, {"MAILAGENT_ENCRYPTION_KEY": b64url(key)}):
        with tempfile.NamedTemporaryFile(suffix=".db", delete=False) as f:
            db_path = f.name

        try:
            storage = SQLiteStorage(db_path)
            await storage.initialize()

            user_id = "delete-me"
            account_id = await storage.save_account(
                user_id=user_id,
                provider="imap",
                email_address="del@test.com",
                credentials={"password": "p"},
            )

            from mailagent.core.types import (
                EmailMessage, ClassificationResult, Draft,
                EmailCategory, EmailAction, DraftStatus
            )
            email = EmailMessage(
                message_id="m1", thread_id="t1", sender="A", sender_email="a@b.com",
                subject="S", body="B", received_at=datetime.now(timezone.utc), raw_headers={}
            )
            email_id = await storage.save_email(email, account_id)
            await storage.save_email_labels(email_id, ["important", "urgent"], source="system")

            clf = ClassificationResult(
                email_id=email_id, category=EmailCategory.MEETS_REPLY,
                priority_score=80, action=EmailAction.REPLY,
                confidence=0.9, reason="test"
            )
            await storage.save_classification(clf)

            draft = Draft(
                email_id=email_id, classification_id="", content="Hi",
                status=DraftStatus.PENDING
            )
            await storage.save_draft(draft)

            counts = await storage.delete_user_data(user_id)

            # Verify all parent/child rows are gone
            async with aiosqlite.connect(db_path) as db:
                for table in ("users", "email_accounts", "emails", "email_labels",
                              "classifications", "drafts"):
                    cursor = await db.execute(f"SELECT COUNT(*) FROM {table}")
                    n = (await cursor.fetchone())[0]
                    assert n == 0, f"Table {table} still has rows after delete_user_data"
        finally:
            os.unlink(db_path)


