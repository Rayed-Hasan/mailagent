# 4. SQLite: encrypted credentials are never stored plaintext
# ---------------------------------------------------------------------------

@pytest.mark.asyncio
async def test_sqlite_credentials_not_in_plaintext():
    """email_accounts.credentials column must contain only encrypted JSON,
    never a plaintext token."""
    from mailagent.core.sqlite_storage import SQLiteStorage
    import aiosqlite

    key = make_32_byte_key()
    with patch.dict(os.environ, {"MAILAGENT_ENCRYPTION_KEY": b64url(key)}):
        with tempfile.NamedTemporaryFile(suffix=".db", delete=False) as f:
            db_path = f.name

        try:
            storage = SQLiteStorage(db_path)
            await storage.initialize()
            secret_token = "oauth2-access-token-secret"
            await storage.save_account(
                user_id="u1",
                provider="gmail",
                email_address="user@example.com",
                credentials={"access_token": secret_token},
            )
            # Read raw DB row — plaintext must NOT appear
            async with aiosqlite.connect(db_path) as db:
                cursor = await db.execute("SELECT credentials FROM email_accounts")
                row = await cursor.fetchone()
            raw = row[0]
            assert secret_token not in raw, "Plaintext credential token found in DB column"
        finally:
            os.unlink(db_path)


